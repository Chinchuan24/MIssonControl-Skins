// A stable pick from a word, so every agent of a role gets the same worker.
export const hashOf = (word: string): number => [...word].reduce((h, ch) => (h * 31 + ch.charCodeAt(0)) >>> 0, 7)

// Sprite pixels to the crab's 30×28 box: the tallest of the crew (48 rows) stands
// 27 high; Smasher towers over the box.
const PIXEL = 0.5625
// A tone just off the dark backgrounds, around the silhouette: no hard outline,
// but the dark clothes still read against the band.
const RIM = '#2A2B3A'

// The sprite as one path per colour and motion group: small enough that a crowd
// of them stays inside the drawing's size limit. Centred in the box, standing on
// its floor; the rows under the gap between the legs are the legs.
export const spriteMarkup = (sp: Sprite, tint: string, box = 30, floor = 27): string => {
  const width = Math.max(...sp.rows.map(r => r.length))
  const height = sp.rows.length
  const mid = Math.floor(width / 2)
  let legFrom = height
  while (legFrom > 0 && (sp.rows[legFrom - 1]?.[mid] ?? '.') === '.' && !sp.float) legFrom--
  if (height - legFrom < 2) legFrom = height
  const colorOf = (ch: string | undefined) => (ch === undefined || ch === '.' ? undefined : ch === 't' && !sp.pal.t ? tint : sp.pal[ch])
  const isFilled = (x: number, y: number) => colorOf(sp.rows[y]?.[x]) !== undefined
  const paths = new Map<string, Map<string, string[]>>()
  const add = (group: string, color: string, x: number, y: number, w: number) => {
    if (!paths.has(group)) paths.set(group, new Map())
    const byColor = paths.get(group) as Map<string, string[]>
    if (!byColor.has(color)) byColor.set(color, [])
    byColor.get(color)?.push(`M${x} ${y}h${w}v1h${-w}z`)
  }
  const side = (x: number) => (x < width / 2 ? 'la' : 'lb')
  // The head: the top sixth, which nods a beat after the breath.
  const headTo = sp.float ? 0 : Math.round(height / 6)
  for (let y = -1; y <= height; y++) {
    const row = sp.rows[y] ?? ''
    for (let x = -1; x <= width; x++) {
      const color = colorOf(row[x])
      if (color === undefined) {
        // The rim: an empty pixel touching the silhouette.
        if (isFilled(x + 1, y) || isFilled(x - 1, y) || isFilled(x, y + 1) || isFilled(x, y - 1)) {
          add(y >= legFrom ? side(x) : y < headTo ? 'hdrim' : 'rim', RIM, x, y, 1)
        }
        continue
      }
      // A run of one letter, split at the middle on the legs so each steps alone.
      const ch = row[x] as string
      let n = 1
      while (row[x + n] === ch && (y < legFrom || side(x + n) === side(x))) n++
      add(y >= legFrom ? side(x) : (sp.cls?.[ch] ?? (y < headTo ? 'hd' : 'bd')), color, x, y, n)
      x += n - 1
    }
  }
  const draw = (group: string) =>
    [...(paths.get(group) ?? new Map<string, string[]>()).entries()].map(([color, d]) => `<path d="${d.join('')}" fill="${color}"/>`).join('')
  const inner = ['hair', 'vis', 'led'].map(g => (paths.has(g) ? `<g class="${g}">${draw(g)}</g>` : '')).join('')
  // The tallest (Smasher) is shrunk to fit the box rather than poke out of it.
  const pixel = Math.min(PIXEL, floor / height)
  const x0 = +((box - width * pixel) / 2).toFixed(2)
  const y0 = +(floor - height * pixel).toFixed(2)
  return `<g transform="translate(${x0},${y0}) scale(${+pixel.toFixed(4)})"><g class="bd">${draw('rim')}${draw('bd')}<g class="hd">${draw('hdrim')}${draw('hd')}</g>${inner}</g><g class="la">${draw('la')}</g><g class="lb">${draw('lb')}</g></g>`
}

