// Casts: pixel characters a skin can put in place of the crabs.
//
// Drawn in one style: no black outline, soft colour blocks, a small faceless head,
// realistic proportions about 46 pixels tall. Generated as pixel-art sheets, then
// cut out, shrunk to the grid and quantised (scripts kept outside the mod).
// The street crew and the corporation are fan homages to Cyberpunk: Edgerunners
// and Cyberpunk 2077 (CD PROJEKT RED / Studio Trigger). No logos are drawn.
//
// A sprite is rows of letters, one per pixel; `.` is empty. `t` takes the tint it
// is drawn with (its role's colour). Letters named in `cls` move on their own:
// `hair` sways, `vis` (a visor, a screen, a cyber-eye) flickers, `led` pulses.
// The rows under the gap between the legs step left and right while it works.

export type Sprite = {
  rows: string[]
  pal: Record<string, string>
  cls?: Record<string, 'hair' | 'vis' | 'led'>
  /** Hovers instead of walking. */
  float?: boolean
}

export type Cast = {
  name: string
  /** What the band calls the boss in place of "Claude". */
  bossName: string
  boss: Sprite
  /** The main characters, by the crab costume a role would have worn. */
  roles: Record<string, Sprite>
  /** The workers: one is picked per role, so a role's agents look alike. */
  crew: Sprite[]
}

